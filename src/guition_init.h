inline void st7701Write9Bit(uint8_t cs, uint8_t sck, uint8_t sda, uint8_t dc, uint8_t data) {
    digitalWrite(cs, LOW);
    delayMicroseconds(2);
    digitalWrite(sck, LOW);
    digitalWrite(sda, dc ? HIGH : LOW);
    delayMicroseconds(2);
    digitalWrite(sck, HIGH);
    delayMicroseconds(2);
    for (int i = 7; i >= 0; i--) {
        digitalWrite(sck, LOW);
        digitalWrite(sda, ((data >> i) & 0x01) ? HIGH : LOW);
        delayMicroseconds(2);
        digitalWrite(sck, HIGH);
        delayMicroseconds(2);
    }
    digitalWrite(cs, HIGH);
    delayMicroseconds(2);
}

inline void st7701Cmd(uint8_t cs, uint8_t sck, uint8_t sda, uint8_t cmd, const uint8_t *data, size_t len) {
    st7701Write9Bit(cs, sck, sda, 0, cmd);
    for (size_t i = 0; i < len; i++) {
        st7701Write9Bit(cs, sck, sda, 1, data[i]);
    }
}

